#!/usr/bin/env bash
set -euo pipefail

# Builds the custom-radio extension into a single classes.dex.
# Usage: extension/build.sh <output.dex>
#
# Reads:
#   F1TV_CUSTOM_AUDIO_URL         Icecast/SHOUTcast MP3 or AAC stream URL (required)
#   F1TV_CUSTOM_AUDIO_ADJUST_MS   Initial sync adjustment in ms (default 0; tune on the TV)
#   F1TV_CUSTOM_AUDIO_FALLBACK_MS Base delay when ClearVR reports no wall clock (default 20000)
#   F1TV_CUSTOM_AUDIO_ENABLED     1/0 - radio on by default (default 1)
#   F1TV_UPDATE_REPO              GitHub owner/repo whose releases the in-app updater follows (empty = off)
#   F1TV_RELEASE_TAG / F1TV_BUILD_RUN  Release tag and CI run id of this build (set by CI)
#   ANDROID_HOME / ANDROID_SDK_ROOT  Android SDK with a platform and build-tools installed

OUT_DEX="$1"
EXT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
[[ -n "${SDK}" && -d "${SDK}" ]] || { echo "ANDROID_HOME/ANDROID_SDK_ROOT not set" >&2; exit 1; }

ANDROID_JAR="$(ls -d "${SDK}"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1)"
[[ -f "${ANDROID_JAR}" ]] || { echo "No platforms/android-*/android.jar in ${SDK}" >&2; exit 1; }
BT_DIR="$(ls -d "${SDK}"/build-tools/*/ 2>/dev/null | sort -V | tail -1)"
D8="${BT_DIR}d8"
[[ -x "${D8}" ]] || D8="${BT_DIR}d8.bat"
[[ -f "${D8}" ]] || { echo "d8 not found in ${BT_DIR}" >&2; exit 1; }
# android.jar has no LambdaMetafactory; build-tools ships the stubs javac needs (as AGP does).
LAMBDA_STUBS="${BT_DIR}core-lambda-stubs.jar"
[[ -f "${LAMBDA_STUBS}" ]] || { echo "core-lambda-stubs.jar not found in ${BT_DIR}" >&2; exit 1; }

URL="${F1TV_CUSTOM_AUDIO_URL:-}"
[[ -n "${URL}" ]] || { echo "F1TV_CUSTOM_AUDIO_URL is empty" >&2; exit 1; }
[[ "${URL}" =~ ^https?:// ]] || { echo "F1TV_CUSTOM_AUDIO_URL must be http(s)" >&2; exit 1; }
ADJUST_MS="${F1TV_CUSTOM_AUDIO_ADJUST_MS:-0}"
FALLBACK_MS="${F1TV_CUSTOM_AUDIO_FALLBACK_MS:-20000}"
[[ "${ADJUST_MS}" =~ ^-?[0-9]+$ && "${FALLBACK_MS}" =~ ^[0-9]+$ ]] || { echo "ms values must be integers" >&2; exit 1; }
ENABLED=true
UPDATE_REPO="${F1TV_UPDATE_REPO:-}"
RELEASE_TAG="${F1TV_RELEASE_TAG:-}"
BUILD_RUN="${F1TV_BUILD_RUN:-}"
for v in "${UPDATE_REPO}" "${RELEASE_TAG}" "${BUILD_RUN}"; do
    [[ "${v}" =~ ^[A-Za-z0-9._/-]*$ ]] || { echo "F1TV_UPDATE_REPO/RELEASE_TAG/BUILD_RUN may only use [A-Za-z0-9._/-]" >&2; exit 1; }
done
[[ "${F1TV_CUSTOM_AUDIO_ENABLED:-1}" == "0" ]] && ENABLED=false

# Git Bash on Windows: hand native tools Windows paths. No-op on Linux/macOS.
native_path() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }
PATH_SEP=":"
command -v cygpath >/dev/null 2>&1 && PATH_SEP=";"

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT
mkdir -p "${WORK}/gen/com/f1tvpatch/radio" "${WORK}/classes" "${WORK}/dex"

# Escape for a Java string literal.
JAVA_URL="$(printf '%s' "${URL}" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
cat > "${WORK}/gen/com/f1tvpatch/radio/Config.java" <<EOF
package com.f1tvpatch.radio;

// Generated by extension/build.sh — do not edit.
final class Config {
    static final String STREAM_URL = "${JAVA_URL}";
    static final long DEFAULT_ADJUST_MS = ${ADJUST_MS}L;
    static final long FALLBACK_DELAY_MS = ${FALLBACK_MS}L;
    static final boolean DEFAULT_ENABLED = ${ENABLED};
    // Self-update (empty repo = off): GitHub "owner/repo", and which release/CI run this build is
    static final String UPDATE_REPO = "${UPDATE_REPO}";
    static final String RELEASE_TAG = "${RELEASE_TAG}";
    static final String BUILD_RUN = "${BUILD_RUN}";

    private Config() { }
}
EOF

# Compile our sources together with the compile-only stubs, then dex ONLY our package:
# the stub classes must never shadow the real F1TV/ClearVR classes at runtime.
SOURCES=()
while IFS= read -r -d '' f; do SOURCES+=("$(native_path "$f")"); done \
    < <(find "${EXT_DIR}/src" "${EXT_DIR}/stubs" "${WORK}/gen" -name '*.java' -print0)
javac -encoding UTF-8 -source 8 -target 8 -nowarn -Xlint:-options \
    -bootclasspath "$(native_path "${ANDROID_JAR}")${PATH_SEP}$(native_path "${LAMBDA_STUBS}")" \
    -d "$(native_path "${WORK}/classes")" "${SOURCES[@]}"
[[ -f "${WORK}/classes/com/f1tvpatch/radio/RadioPatch.class" ]] || { echo "javac failed" >&2; exit 1; }

CLASS_FILES=()
while IFS= read -r -d '' f; do CLASS_FILES+=("$(native_path "$f")"); done \
    < <(find "${WORK}/classes/com/f1tvpatch" -name '*.class' -print0)
"${D8}" --release --min-api 23 \
    --lib "$(native_path "${ANDROID_JAR}")" --classpath "$(native_path "${WORK}/classes")" \
    --output "$(native_path "${WORK}/dex")" "${CLASS_FILES[@]}"
[[ -f "${WORK}/dex/classes.dex" ]] || { echo "d8 failed" >&2; exit 1; }
cp "${WORK}/dex/classes.dex" "${OUT_DEX}"
echo "Built ${OUT_DEX}"
